#!/usr/bin/env python3
"""Rebuild the tiny, asset-independent TES3 test-cell plugin (no game data read)."""

from pathlib import Path
import struct


def sub(name, data):
    return name.encode("ascii") + struct.pack("<I", len(data)) + data


def record(name, data):
    return name.encode("ascii") + struct.pack("<III", len(data), 0, 0) + data


def string(value):
    return value.encode("ascii") + b"\0"


def main():
    header = record("TES3", sub("HEDR", struct.pack(
        "<fI32s256sI", 1.3, 0, b"OpenMW ragdoll development",
        b"Isolated flat ragdoll test floor. Generated by tools/make-ragdoll-test-area.py.", 2)))
    floor = record("STAT", sub("NAME", string("openmw_ragdoll_test_floor"))
                   + sub("MODL", string("ragdoll_test_floor.osgt")))
    cell = record("CELL", sub("NAME", string("OpenMW Ragdoll Test Floor"))
                  + sub("DATA", struct.pack("<Iii", 1, 0, 0))  # Interior; no water.
                  + sub("AMBI", struct.pack("<IIIf", 0x00B0B0B0, 0x00606060, 0x00202020, 0.0))
                  + sub("NAM0", struct.pack("<I", 1))
                  + sub("FRMR", struct.pack("<I", 1))
                  + sub("NAME", string("openmw_ragdoll_test_floor"))
                  + sub("DATA", struct.pack("<6f", 0, 0, 0, 0, 0, 0)))
    target = Path(__file__).resolve().parents[1] / "scripts/data/ragdoll_manual/ragdoll_test_area.omwaddon"
    target.write_bytes(header + floor + cell)
    print(f"Wrote {target} ({target.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
