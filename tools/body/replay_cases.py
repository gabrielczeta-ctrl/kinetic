"""Play bookmarks as test input: the user's raw mouse and left button, step by
step, from a quiet guard before each bookmark to just after it, written as
scripts/data/integration_tests/test_combat_fixes/replay_inputs.lua for the
REPLAY-01 test (2026-10-04: the stuck guards and spins of the user's build 47
sessions did not come back with scripted strokes).

Per case: the weapon, first person or not, the steps (dx, dy raw counts,
y down; the button held), and what the recording measured each step (the
physical blade's angle from the commanded one, the hand's distance from its
goal) to compare with.

usage: python tools/body/replay_cases.py RECORDING_DIR:BOOKMARK[,BOOKMARK,tTICK] [...]
(tTICK: the moment at that physics step, for stretches with no bookmark)
"""
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import mouse_view  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / 'scripts/data/integration_tests/test_combat_fixes/replay_inputs.lua'


def angle(a, b):
    if not a or not b:
        return -1
    return math.degrees(math.acos(max(-1.0, min(1.0, sum(x * y for x, y in zip(a, b))))))


def cases(directory, marks, ticks=()):
    directory = directory.rstrip('/\\')
    if not Path(directory, 'ticks-0.jsonl').exists():
        directory += '/manual-recording'
    data = mouse_view.convert(directory)
    c = data['cols']
    index = {t: i for i, t in enumerate(c['t'])}
    first_person, motion = {}, {}
    for row in mouse_view.rows(directory):
        if row.get('kind') == 'tick':
            first_person[row['tick']] = row.get('first_person', 1)
            e = row.get('eye_dir', [0, 0, 0])
            pitch = math.asin(max(-1.0, min(1.0, -e[2]))) if any(e) else 0.0
            motion[row['tick']] = (row.get('move', [0, 0, 0]), row.get('actor_yaw', 0.0), pitch)
    out = []
    # bookmarks by id, or moments by tick ("t35568": a stretch with no bookmark)
    picked = [m for m in data['bookmarks'] if m['id'] in marks]
    picked += [{'id': 't%d' % m, 'tick': m, 'note': 'tick %d' % m} for m in ticks if m in index]
    for mark in picked:
        end = index[mark['tick']]
        # back from 5 s before the bookmark to a guard at rest for 0.5 s
        start = max(0, end - 300)
        while start > 30 and end - start < 1500:  # at most 25 s back
            window = range(start - 30, start)
            if all((c['hsc'][k] or {}).get('stage', 0) == 0 and not c['lmb'][k] for k in window):
                break
            start -= 1
        steps = []
        previous_yaw = None
        for k in range(start, min(len(c['t']), end + 31)):
            move, yaw, pitch = motion.get(c['t'][k], ([0, 0, 0], 0.0, 0.0))
            turn = 0.0 if previous_yaw is None else (yaw - previous_yaw + math.pi) % (2 * math.pi) - math.pi
            previous_yaw = yaw
            steps.append([c['mx'][k], -c['my'][k], c['lmb'][k],
                          round(angle(c['bp'][k], c['bc'][k])),
                          round(math.dist(c['hp'][k], c['hc'][k]), 1) if c['hp'][k] and c['hc'][k] else -1,
                          round((c['hsc'][k] or {}).get('wrist_err', -1)),
                          round(move[0], 2), round(move[1], 2), int(move[2]), round(turn, 4), round(pitch, 3)])
        out.append({'name': '%s #%s' % (Path(directory).parent.name[-16:], mark['id']),
                    'note': mark['note'][:80], 'weapon': data['weapons'][c['wpn'][end]],
                    'firstPerson': bool(first_person.get(c['t'][end], 1)), 'bookmarkStep': end - start + 1,
                    'steps': steps})
    return out


def main():
    all_cases = []
    for arg in sys.argv[1:]:
        directory, marks = arg.rsplit(':', 1)
        items = marks.split(',')
        all_cases += cases(directory, {int(m) for m in items if not m.startswith('t')},
                           [int(m[1:]) for m in items if m.startswith('t')])
    lines = ['-- Generated by tools/body/replay_cases.py: the user\'s play input before bookmarks.',
             '-- steps: { dx, dy (raw counts, y down), button held, recorded blade off (deg), recorded hand error,',
             '--         recorded hand rotation error (deg, blade and roll), side, forward, run,',
             '--         turn this step (rad), look pitch (rad) }',
             'return {']
    for case in all_cases:
        lines.append('  { name = %s, note = %s, weapon = %s, firstPerson = %s, bookmarkStep = %d, steps = {'
                     % (json.dumps(case['name']), json.dumps(case['note']), json.dumps(case['weapon']),
                        'true' if case['firstPerson'] else 'false', case['bookmarkStep']))
        for i in range(0, len(case['steps']), 8):
            lines.append('    ' + ' '.join('{%d,%d,%d,%d,%s,%d,%s,%s,%d,%s,%s},' % tuple(s)
                                           for s in case['steps'][i:i + 8]))
        lines.append('  } },')
    lines.append('}')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    for case in all_cases:
        print('%-22s %-15s %4d steps, bookmark at %d: %s' % (case['name'], case['weapon'], len(case['steps']),
                                                             case['bookmarkStep'], case['note']))


if __name__ == '__main__':
    main()
